need(js,/padoka_create_order_once'/,'caminho sem cupom perdeu RPC idempotente compatível');
need(js,/request_id/,'checkout perdeu request_id');
need(html,/data-feature="coupons"/,'UI de cupom não está atrás de feature flag');
need(html,/padoka_coupon_preview/,'UI não valida cupom no servidor');
