import fs from 'node:fs';
const edge=fs.readFileSync('supabase/functions/padoka-telemetry/index.ts','utf8');
const browser=fs.readFileSync('assets/telemetry.js','utf8');
const fail=m=>{console.error('FAIL:',m);process.exitCode=1};
const need=(s,r,m)=>{if(!r.test(s))fail(m)};
need(edge,/ALLOWED_ORIGINS\s*=\s*new Set/,'telemetry sem allowlist de origem');
need(edge,/if \(!origin \|\| !ALLOWED_ORIGINS\.has\(origin\)\)/,'telemetry não rejeita origem ausente/desconhecida');
need(edge,/EVENTS\s*=\s*new Set/,'event whitelist ausente');
need(edge,/META_KEYS\s*=\s*new Set/,'metadata whitelist ausente');
need(edge,/\[email\]/,'scrub de e-mail ausente');
need(edge,/\[phone\]/,'scrub de telefone ausente');
need(edge,/>= 90/,'rate limit por sessão ausente');
need(edge,/padoka_client_events/,'persistência de telemetria ausente');
need(edge,/padoka_incidents/,'agregação de incidentes ausente');
need(edge,/SUPABASE_SECRET_KEYS/,'secret key moderna não é preferida');
need(browser,/largest-contentful-paint/,'LCP não coletado');
need(browser,/layout-shift/,'CLS não coletado');
need(browser,/durationThreshold:40/,'INP/event timing não coletado');
need(browser,/unhandledrejection/,'rejeições não observadas');
if(/user\.email|profile\.phone|localStorage/.test(browser))fail('telemetria não deve ler dados pessoais/armazenamento persistente');
if(!process.exitCode)console.log('Telemetry edge audit: OK');
