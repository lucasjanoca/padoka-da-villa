import fs from 'node:fs';
const sql=fs.readFileSync('supabase/041_enterprise_observability.sql','utf8');
const page=fs.readFileSync('enterprise.html','utf8');
const flags=fs.readFileSync('assets/feature-flags.js','utf8');
const fail=m=>{console.error('FAIL:',m);process.exitCode=1};
const need=(s,r,m)=>{if(!r.test(s))fail(m)};
need(sql,/create table if not exists public\.padoka_feature_flags/i,'feature flags table ausente');
need(sql,/create table if not exists public\.padoka_client_events/i,'telemetry table ausente');
need(sql,/create table if not exists public\.padoka_incidents/i,'incident table ausente');
need(sql,/alter table public\.padoka_(?:feature_flags|client_events|incidents) enable row level security/i,'RLS enterprise ausente');
need(sql,/padoka_enterprise_metrics/i,'enterprise metrics RPC ausente');
need(sql,/padoka_health_summary/i,'health summary RPC ausente');
need(sql,/coalesce\(auth\.jwt\(\)->>'aal','aal1'\)\s*=\s*'aal2'/i,'feature flag mutation sem AAL2');
need(page,/getAuthenticatorAssuranceLevel/,'enterprise page não valida MFA');
need(page,/\['owner','manager'\]/,'enterprise page sem allowlist owner manager');
need(page,/padoka_health_summary/,'enterprise page sem health summary');
need(page,/padoka_enterprise_metrics/,'enterprise page sem funil');
need(page,/padoka_incidents/,'enterprise page sem incidentes');
need(page,/padoka_feature_flags/,'enterprise page sem feature flags');
need(flags,/fail-closed/i,'feature flags não documentam fail-closed');
need(flags,/apikey:cfg\.publishableKey/,'feature flags não usam publishable key via apikey');
if(/Authorization:\s*['`]Bearer/i.test(flags))fail('publishable key não deve ser tratada como Bearer de usuário');
if(!process.exitCode)console.log('Enterprise observability audit: OK');
