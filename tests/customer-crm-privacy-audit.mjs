import fs from 'node:fs';
const sql=fs.readFileSync('supabase/042_customer_crm_privacy.sql','utf8');
const hard=fs.readFileSync('supabase/045_private_crm_trigger_functions.sql','utf8');
const page=fs.readFileSync('conta.html','utf8');
const fail=m=>{console.error('FAIL:',m);process.exitCode=1};
const need=(s,r,m)=>{if(!r.test(s))fail(m)};
for(const table of ['padoka_loyalty_accounts','padoka_loyalty_ledger','padoka_customer_notifications','padoka_privacy_requests'])need(sql,new RegExp('create table if not exists public\\.'+table,'i'),table+' ausente');
need(sql,/not o\.is_test|new\.is_test/i,'fidelidade precisa excluir pedidos de teste');
need(sql,/payment_status not in \('paid','paid_late'\)/i,'fidelidade precisa exigir pagamento real');
need(sql,/status<>'completed'/i,'fidelidade precisa exigir pedido concluído');
need(sql,/user_id=auth\.uid\(\)/i,'RLS de cliente precisa vincular auth.uid');
need(sql,/padoka_export_my_data/i,'exportação de dados ausente');
need(sql,/padoka_request_privacy_action/i,'solicitação de privacidade ausente');
need(hard,/set schema padoka_private/i,'trigger functions de CRM não foram movidas ao schema privado');
need(hard,/revoke all on function padoka_private\.padoka_order_customer_notifications\(\) from public, anon, authenticated/i,'trigger de notificações ainda é executável pelo cliente');
need(hard,/revoke all on function padoka_private\.padoka_award_loyalty_on_real_order\(\) from public, anon, authenticated/i,'trigger de fidelidade ainda é executável pelo cliente');
need(page,/data-feature="loyalty"/,'conta sem feature flag de fidelidade');
need(page,/data-feature="customer_notifications"/,'conta sem notificações');
need(page,/data-feature="privacy_self_service"/,'conta sem privacidade');
need(page,/padoka_export_my_data/,'conta não exporta dados via RPC');
need(page,/padoka_request_privacy_action/,'conta não abre solicitação via RPC');
need(page,/data-reorder/,'comprar novamente ausente');
if(!process.exitCode)console.log('Customer CRM/privacy audit: OK');
